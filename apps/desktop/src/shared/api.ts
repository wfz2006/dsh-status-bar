import type { Projection } from '@glass/protocol';
import type { Bounds } from './window';
import type { GlassViewMode, GlassSettings } from './view-model';
import type { DesktopOpticsState, DesktopOpticsFrame,DesktopOpticsBounds } from './desktop-optics';
import type { EdgeMotion, EdgeSide } from './edge-dock';
export type WindowAction = 'expand' | 'overview' | 'collapse' | 'restore-capsule' | 'hide' | 'quit' | 'pin' | 'settings' | 'activity' | 'back' | 'approval' | 'menu' | 'open-dsh' | 'reconnect' | 'details' | 'other-requests' | 'introduce-whale-pool' | 'try-whale-pool' | 'dismiss-whale-pool';
export type MockAction = 'restart' | 'disconnect' | 'reconnect' | 'out-of-order' | 'approval-queue' | 'edge-cases' | 'completed' | 'long-approval';
export type PresentationState = { material: 'acrylic' | 'clear' | 'solid' | 'frosted'; morphing: 'expanding' | 'collapsing' | null };
export type RequestKind = 'approval' | 'question';
export type SubmissionResult = { id: string; kind: RequestKind; identity: RequestIdentity; sessionTitle: string;
  decision?: 'allowed-once' | 'rejected'; status: 'submitting' | 'confirmed' | 'unconfirmed' };
export type WindowState = PresentationState & { visible?: boolean; pinned: boolean; viewMode: GlassViewMode; manualSize: boolean;
  panel: 'settings' | 'activity' | 'whale-pool-intro' | 'other-requests' | null;
  settings: GlassSettings; completionFeedback: boolean; dockEdge?: EdgeSide; edgeMotion?: EdgeMotion;
  submissions?: SubmissionResult[]; reconnectFocus?: number; recoveryHint?: string; hideBlocked?: boolean };
export type SourceState = { mode: 'mock' | 'dsh'; connection: 'disconnected' | 'connecting' | 'connected'; endpoint: string | null; error: string | null };
export type RequestIdentity = { runtimeId: string; sourceEpoch: string; sessionId: string; requestId: string };
export type QuestionAnswers = Array<{ questionId: string; values: string[] }>;
export type HistoryPagination = { hasOlder: boolean; canReturn: boolean };
export type PoolEvent = { id: number; sessionId: string; kind: 'completed' | 'other-request' };
export type DesktopProjection = Projection & { selectedSession?: string; history?: HistoryPagination; draftScope?: string; poolEvent?: PoolEvent };
export interface GlassAPI {
  getSourceState(): Promise<SourceState>;
  subscribeSourceState(callback: (state: SourceState) => void): () => void;
  connectDSH(url: string): Promise<void>;
  disconnectDSH(): Promise<void>;
  useMock(): Promise<void>;
  respondApproval(identity: RequestIdentity, outcome: 'allowed-once' | 'rejected'): Promise<void>;
  respondQuestion(identity: RequestIdentity, answers: QuestionAnswers): Promise<void>;
  getOpticsState(): Promise<DesktopOpticsState>;
  setOpticsEnabled(enabled:boolean): Promise<DesktopOpticsState>;
  subscribeOpticsState(callback:(state:DesktopOpticsState)=>void):()=>void;
  subscribeOpticsFrame(callback:(frame:DesktopOpticsFrame)=>void):()=>void;
  subscribeOpticsPosition(callback:(bounds:DesktopOpticsBounds)=>void):()=>void;
  getState(): Promise<DesktopProjection>;
  subscribe(callback: (state: DesktopProjection) => void): () => void;
  getWindowState(): Promise<WindowState>;
  subscribeWindow(callback: (state: WindowState) => void): () => void;
  windowAction(action: WindowAction, reduceMotion?: boolean): Promise<WindowState>;
  resizeWindow(bounds: Bounds): Promise<void>;
  moveWindow(position: { x: number; y: number }, released?: boolean): Promise<void>;
  setSettings(settings: Partial<GlassSettings>): Promise<WindowState>;
  selectSession(id: string, previous?: { runtimeId: string | null; epoch: string | null; sessionId: string }): Promise<void>;
  loadHistory(direction: 'older' | 'recent'): Promise<void>;
  openRequest(kind: RequestKind, identity: RequestIdentity, reduceMotion?: boolean): Promise<WindowState>;
  dismissSubmission(id: string): Promise<void>;
  copyApproval(identity: { sessionId: string; requestId: string }): Promise<void>;
  mockAction(action: MockAction): Promise<void>;
}
